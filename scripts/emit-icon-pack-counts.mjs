// Write src/data/iconPackCounts.generated.js: how many icons each pack lists, read from the
// committed snapshots in public/iconify/collections/.
//
//   node scripts/emit-icon-pack-counts.mjs
//
// The signed-out gate quotes "Log in to access N icons" where N is every icon a free account
// can open. The snapshots are 1 MB together, so the page cannot read them to count; this
// writes the counts the page needs into a small module instead. Each entry is
// `[all, proOnly]`: the names the pack lists, and how many of those PRO_ONLY_ICONS keeps back
// for Pro. snapshot-icon-collections.mjs runs this at the end, and
// tests/unit/icon-pack-counts.test.js fails if the file and the snapshots disagree.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { proOnlyIconCount } from '../src/data/iconPackTiers.js'
import { COLLECTION_SNAPSHOT_PATH } from '../src/utils/iconCollectionSnapshot.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SNAPSHOT_DIR = path.join(root, 'public', ...COLLECTION_SNAPSHOT_PATH.split('/').filter(Boolean))
export const COUNTS_FILE = path.join(root, 'src', 'data', 'iconPackCounts.generated.js')

/** The names a snapshot lists: the uncategorised ones plus every category's. */
export function snapshotNames(d) {
  return [...new Set([...(d.uncategorized || []), ...Object.values(d.categories || {}).flat()])]
}

/** `{ prefix: [all, proOnly] }` for every snapshot on disk, sorted by prefix. */
export async function readCounts() {
  const files = (await readdir(SNAPSHOT_DIR)).filter((f) => f.endsWith('.json')).sort()
  const out = {}
  for (const f of files) {
    const prefix = f.slice(0, -5)
    const names = snapshotNames(JSON.parse(await readFile(path.join(SNAPSHOT_DIR, f), 'utf8')))
    out[prefix] = [names.length, proOnlyIconCount(prefix, names)]
  }
  return out
}

export function render(counts) {
  const rows = Object.entries(counts).map(([p, v]) => `  ${JSON.stringify(p)}: [${v[0]}, ${v[1]}],`).join('\n')
  return `// GENERATED by scripts/emit-icon-pack-counts.mjs from public/iconify/collections/.
// Do not edit by hand: run \`node scripts/emit-icon-pack-counts.mjs\`.
// Per pack: [icons it lists, icons of those that only Pro opens].

export const ICON_PACK_COUNTS = Object.freeze({
${rows}
})
`
}

export async function writeCounts() {
  const counts = await readCounts()
  await writeFile(COUNTS_FILE, render(counts))
  return counts
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const counts = await writeCounts()
  console.log(`wrote ${Object.keys(counts).length} pack counts to ${path.relative(root, COUNTS_FILE)}`)
}
