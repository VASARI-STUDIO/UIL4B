// Writes api/_lib/exportThemes/engine/scenes.js from the export engine's mockup scene library.
//   node scripts/export-scenes-gen.mjs <path to export-systems/engine/scenes>
// Only the numbers a layout reads are kept (size, surfaces, quad corners and aspect, tags); the photographs and masks stay out,
// because a slot export draws no mockup and the server function must stay small.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, 'index.json'))) {
  console.error('usage: node scripts/export-scenes-gen.mjs <export-systems/engine/scenes>');
  process.exit(1);
}
const out = fileURLToPath(new URL('../api/_lib/exportThemes/engine/scenes.js', import.meta.url));
const index = JSON.parse(fs.readFileSync(path.join(src, 'index.json'), 'utf8')).scenes;
const lines = index.map((entry) => {
  const meta = JSON.parse(fs.readFileSync(path.join(src, entry.id, 'scene.json'), 'utf8'));
  const quads = meta.quads.map((q) => ({ corners: q.corners, kind: q.kind, aspect: q.aspect }));
  return `  ${JSON.stringify(entry.id)}: ${JSON.stringify({ ...entry, w: meta.w, h: meta.h, quads })},`;
});
const text = `// GENERATED by scripts/export-scenes-gen.mjs from the export engine's mockup scene library. Do not edit by hand.
// The geometry of every mockup scene (size, surfaces, quad corners and aspect). A slot export draws no photograph, so no image is held here.
export const SCENES = {
${lines.join('\n')}
};
`;
fs.writeFileSync(out, text);
console.log(`${index.length} scenes, ${text.length} bytes -> ${path.relative(process.cwd(), out)}`);
