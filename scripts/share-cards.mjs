/**
 * The sections, in the order they are drawn.
 *
 * `hue` names a `--hue-*` custom property in src/styles/global.css; the
 * generator reads the real hex out of that file rather than restating it, so a
 * brand colour change moves the cards. `group` names a CREATE_GROUPS id, and
 * the tool names printed on a card are read from that group — a new tool
 * appears on its section's card the next time the cards are generated, with no
 * edit here.
 */
const listOf = (items) => items.length < 2
  ? items.join('')
  : `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`

