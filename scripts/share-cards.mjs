// WHICH SHARE CARD EACH ROUTE UNFURLS AS.
//
// ── The gap ─────────────────────────────────────────────────────────────────
//
// scripts/prerender.mjs rewrites title, description, canonical, og:title,
// og:description, og:url, twitter:title and twitter:description per route — but
// not og:image or twitter:image. So all 28 shells pointed at the one card at
// /previews/og-image.png, and a link to the Contrast Checker posted in Slack
// looked exactly like a link to the homepage. The words were right and the
// picture was wrong, and the picture is the half people actually look at.
//
// ── The decision: one card per SECTION, not per route ───────────────────────
//
// Three options were on the table.
//
// PER-ROUTE ART, generated at build time from project data. The app does know
// its own palettes, gradients and type scales, so it could draw 28 distinct
// cards. The cost is not the drawing — it is that a share card is mostly TYPE,
// and rasterising type needs a real renderer. Node has no canvas; adding sharp
// or resvg means a native binary in the Vercel build for a picture. Making the
// build depend on Chromium is worse still: a browser download in CI, on the
// critical path of every deploy, to redraw seven images that change about twice
// a year.
//
// HAND-MADE CARDS for the few routes that matter. Cheapest to ship and the
// worst to maintain: it needs a designer for every new tool, and a tool that
// ships without one silently falls back to the homepage card — the exact
// failure being fixed, re-armed for every future route.
//
// ONE CARD PER SECTION — chosen. A tool page unfurling as its own CATEGORY
// closes most of the gap: a reader who sees "Colour" knows what the link is,
// which they did not when it said "Design Toolkit". It is 7 images rather than
// 28, every one drawn by the same generator from the same tokens, and a NEW
// TOOL INHERITS ITS SECTION'S CARD AUTOMATICALLY rather than falling back to
// the homepage. That last property is what settled it: the fallback for a route
// nobody thought about is its section, not the wrong picture.
//
// The cards are generated by `npm run og:cards` (scripts/og-cards.mjs, which is
// where the Chromium dependency lives) and committed, exactly like vercel.json
// is generated by `npm run sync:rewrites` and committed. Build-time cost: zero.
// tests/unit/share-cards.test.js fails if a card file is missing, if a route
// maps to nothing, or if the design tokens the cards were drawn from have moved
// since — which is the "committed artefact goes stale" failure that would
// otherwise be silent.
//
// ── Learn is a section since 2026-09-08 ─────────────────────────────────────
//
// /learn and every /learn/<slug> guide used to fall back to the homepage card,
// which the learn-content row in pipeline.js listed as a gap from the day the
// first guide shipped. The Learn card is drawn in the same system as the tool
// sections, and its subject is the section's real content: the guides, by the
// nav label each carries in learnIndex.js, and a blurb that COUNTS them. Both
// are derived from the registry rather than typed, and so are the routes — so
// a new guide inherits the card and, because cards.json records the guide
// list, fails tests/unit/share-cards.test.js until the card is redrawn with it.
//
// ── Nine routes deliberately keep the homepage card ────────────────────────
//
// /home IS the homepage, so the homepage card is the correct picture, not a
// fallback. The support and legal pages (/help, /info, /feedback, /privacy,
// /terms, /sitemap, /community) are site chrome rather than a product area;
// inventing a "Legal" card for them would be drawing seven images to say
// nothing. /seo is a real tool with no section of its own — flagged rather than
// forced into a category it does not belong to.
