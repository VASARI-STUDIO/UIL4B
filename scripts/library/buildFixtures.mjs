// Writes api/_lib/library/fixtures.js: stand-in library data for development
// and tests when neither the fetched Pro data (api/_lib/pro/) nor the in-tree
// copies are present.
//
// It is built ONLY from the public client stubs in src/data/, so it can never
// carry a Pro value. Free rows are copied as they already are in public; each
// locked row keeps its id, order, flags, tags, category and slot count, and
// gets obviously fake values (#FF00FF swatches, placeholder prompt text). The
// free split and the emitted client stubs are therefore identical to the real
// data's, which is what the API and the client tests depend on.
//
// The API never serves these in production (load.js refuses them there).
//
// Run: node scripts/library/buildFixtures.mjs   (rerun after the stubs change)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { LIBRARY_PALETTE_ROWS, BRAND_ROWS } from '../../src/data/paletteLibrary.js'
import { LIBRARY_GRADIENT_ROWS } from '../../src/data/gradientLibrary.js'
import { COMMUNITY_PROMPT_ROWS } from '../../src/data/communityPrompts.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = path.join(ROOT, 'api', '_lib', 'library', 'fixtures.js')
export const FIXTURE_MARKER = 'UIL4B-FAKE-FIXTURE'
const FAKE = '#FF00FF'

const fakeColors = (n) => Array.from({ length: n }, () => FAKE)
const fakeStops = (n) => Array.from({ length: n }, (_, i) => ({
  color: FAKE,
  position: n === 1 ? 0 : Math.round((100 * i) / (n - 1)),
}))

export function buildFixtures() {
  // Palette Gallery rows are the curated library rows without their `kind`.
  const gallery = LIBRARY_PALETTE_ROWS.filter((r) => r.kind === 'curated').map((r) => {
    const { kind: _kind, slots, colors, ...rest } = r
    return { ...rest, colors: colors ? [...colors] : fakeColors(slots) }
  })
  // Brand rows: free ones are public in full; Pro ones keep their slot count.
  const brands = BRAND_ROWS.map((r) => {
    if (r.free === true) return { id: r.id, name: r.name, free: true, system: r.system, colors: [...r.colors] }
    return { id: r.id, name: r.name, free: false, system: 'custom', colors: fakeColors(r.slots) }
  })
  // The library's brand rows must agree with the brand list, or the derived
  // rows below would drift from the stubs.
  const libBrands = LIBRARY_PALETTE_ROWS.filter((r) => r.kind === 'brand')
  const derived = brands.map((b) => `brand-${b.id}:${!b.free}`).join()
  const listed = libBrands.map((r) => `${r.id}:${r.pro === true}`).join()
  if (derived !== listed) throw new Error('LIBRARY_PALETTE_ROWS brand rows disagree with BRAND_ROWS')

  const gradients = LIBRARY_GRADIENT_ROWS.map((r) => {
    if (Array.isArray(r.stops)) return structuredClone(r)
    return { id: r.id, name: r.name, type: 'Linear', angle: 135, stops: fakeStops(r.slots), tags: ['fixture'] }
  })
  const prompts = COMMUNITY_PROMPT_ROWS.map((r) => {
    if (typeof r.text === 'string') return { ...r }
    return {
      id: r.id,
      free: r.free,
      category: r.category,
      title: `Fixture prompt ${r.id}`,
      text: `FIXTURE: placeholder prompt for ${r.id}`,
      tags: r.tags,
      img: '',
      author: 'Fixture',
      saves: 0,
    }
  })
  return { gallery, brands, gradients, prompts }
}

export function renderFixtures({ gallery, brands, gradients, prompts }) {
  // One row per line keeps the diff readable when a stub changes.
  const json = (rows) => ['[', ...rows.map((r) => `  ${JSON.stringify(r)},`), ']'].join('\n')
  return `// GENERATED by scripts/library/buildFixtures.mjs. Do not edit by hand.
// ${FIXTURE_MARKER}: stand-in library data built only from the public stubs in
// src/data/. Locked rows carry fake values. Never served in production.
export const FIXTURE_MARKER = '${FIXTURE_MARKER}'

export const GALLERY_PALETTES = ${json(gallery)}

export const BRAND_PALETTES = ${json(brands)}

export const CURATED_LIBRARY_PALETTES = GALLERY_PALETTES.map((p) => ({ ...p, kind: 'curated' }))

export const BRAND_LIBRARY_PALETTES = BRAND_PALETTES.map((b) => ({
  id: \`brand-\${b.id}\`,
  name: b.name,
  colors: b.colors,
  kind: 'brand',
  pro: !b.free,
  system: b.system,
}))

export const LIBRARY_PALETTES = [...CURATED_LIBRARY_PALETTES, ...BRAND_LIBRARY_PALETTES]

export const GALLERY_GRADIENTS = ${json(gradients)}

export const COMMUNITY_PROMPTS = ${json(prompts)}
`
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  fs.writeFileSync(OUT, renderFixtures(buildFixtures()))
  console.log(`wrote ${path.relative(ROOT, OUT)}`)
}
