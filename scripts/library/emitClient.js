// Writes the browser's copy of the libraries (src/data/) from the server data.
//
//   node scripts/library/emitClient.js
//
// The output holds free rows in full and Pro rows as stubs (clientRows.js).
// tests/unit/pro-library-server-only.test.js renders the same text and fails if
// the committed files differ, so run this after editing any server library.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { clientRows, brandRows, freeSplit, libraryTotals } from './clientRows.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const HEADER = (name) => `// GENERATED by scripts/library/emitClient.js from the server-only library data.
// Do not edit by hand: run \`node scripts/library/emitClient.js\`.
// ${name}
`

const lines = (rows, indent) => rows.map((row) => `  ${indent ? JSON.stringify(row, null, 2).replace(/\n/g, '\n  ') : JSON.stringify(row)},`).join('\n')

export function renderClientFiles() {
  const firstPalette = freeSplit('palettes').open[0]
  const firstGradient = freeSplit('gradients').open[0]
  return {
    'src/data/libraryTotals.js': `${HEADER('True library sizes, and the lead item of each, for surfaces that print a count without holding the rows.')}
export const LIBRARY_TOTALS = Object.freeze(${JSON.stringify(libraryTotals(), null, 2)})

// The first row of each library. Always a free row.
export const LIBRARY_LEAD = Object.freeze({
  palette: ${JSON.stringify(firstPalette)},
  gradient: ${JSON.stringify(firstGradient)},
})
`,
    'src/data/paletteLibrary.js': `${HEADER('Palette Library rows in canonical order: full where a free account may open them, stubs elsewhere.')}
export const LIBRARY_PALETTE_ROWS = [
${lines(clientRows('palettes'))}
]

// The Palette Builder's Brands panel: free brands in full, Pro brands as stubs.
export const BRAND_ROWS = [
${lines(brandRows())}
]
`,
    'src/data/gradientLibrary.js': `${HEADER('Gradient Library rows in canonical order: full where a free account may open them, stubs elsewhere.')}
export const LIBRARY_GRADIENT_ROWS = [
${lines(clientRows('gradients'))}
]
`,
    'src/data/communityPrompts.js': `${HEADER('Community prompt rows in canonical order: full where free, tag-only stubs elsewhere.')}
export const COMMUNITY_PROMPT_ROWS = [
${lines(clientRows('prompts'), true)}
]
`,
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [file, text] of Object.entries(renderClientFiles())) {
    fs.writeFileSync(path.join(ROOT, file), text, 'utf8')
    console.log('wrote', file)
  }
}
