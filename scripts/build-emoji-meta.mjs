// Generates two files the Emoji Library's detail dialog reads:
//
//   src/data/emojiShortcodes.txt  chat shortcodes and the Unicode version, from
//                                 GitHub's gemoji list (MIT).
//   src/data/emojiTones.js        which catalogue emoji take a skin tone, proved
//                                 against the Unicode emoji-test file.
//
// A shortcode is looked up, never made up: an emoji with no gemoji entry stops
// the run. A tone is accepted only when composeSkinTone() yields, for all five
// tones, a sequence Unicode lists as an emoji.
//
//   node scripts/build-emoji-meta.mjs
//
// Needs network access. Not part of `npm run build`: the generated files are
// committed, so a build never depends on a third party being up.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { EMOJI_DATA } from '../src/data/emojiData.js'
import { SKIN_TONES, composeSkinTone } from '../src/utils/emojiSkinTone.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const DATA = path.join(HERE, '..', 'src', 'data')
const GEMOJI = 'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json'
const EMOJI_TEST = 'https://unicode.org/Public/emoji/latest/emoji-test.txt'

const bare = s => s.replace(/️/g, '')

async function get(url, kind) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`)
  return kind === 'json' ? res.json() : res.text()
}

const chars = []
for (const g of EMOJI_DATA) for (const c of g.emojis.split(/\s+/).filter(Boolean)) if (!chars.includes(c)) chars.push(c)

// ── Shortcodes ──
const gemoji = await get(GEMOJI, 'json')
const byChar = new Map(gemoji.map(e => [bare(e.emoji), e]))
const lines = []
const missing = []
for (const c of chars) {
  const hit = byChar.get(bare(c))
  if (!hit || !hit.aliases?.length) { missing.push(c); continue }
  lines.push(`${c}\t${hit.aliases.join('|')}\t${hit.unicode_version || ''}`)
}
if (missing.length) {
  console.error(`No gemoji entry for ${missing.length} emoji: ${missing.join(' ')}`)
  process.exit(1)
}
fs.writeFileSync(path.join(DATA, 'emojiShortcodes.txt'), lines.join('\n') + '\n', 'utf8')
console.log(`wrote emojiShortcodes.txt — ${lines.length} emoji`)

// ── Skin tones ──
const known = new Set()
for (const line of (await get(EMOJI_TEST, 'text')).split('\n')) {
  if (!line || line.startsWith('#')) continue
  const m = line.match(/^([0-9A-F ]+)\s*;\s*(fully-qualified|minimally-qualified)/)
  if (m) known.add(bare(m[1].trim().split(/\s+/).map(h => String.fromCodePoint(parseInt(h, 16))).join('')))
}
const toned = chars.filter(c => SKIN_TONES.every(t => { const v = composeSkinTone(c, t.mark); return v !== composeSkinTone(c, "") && known.has(bare(v)) }))
const out = `// GENERATED by scripts/build-emoji-meta.mjs — do not edit by hand.
// The catalogue emoji that take a skin tone: each one has a Unicode-defined
// toned form for all five tones when composed by composeSkinTone().
export const TONE_EMOJI = new Set(${JSON.stringify(toned.join(' '))}.split(' '))
`
fs.writeFileSync(path.join(DATA, 'emojiTones.js'), out, 'utf8')
console.log(`wrote emojiTones.js — ${toned.length} of ${chars.length} emoji take a tone`)
